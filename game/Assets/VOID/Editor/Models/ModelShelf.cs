        [MenuItem("VOID/Env/Models/Shelf")]
        public static void Build()
        {
            var b = new PBKit.Builder();

            // ---------- корпус: боковины, задняя стенка, дно, четыре полки и крышка
            b.Box(new Vector3(-0.491f, 1.0f, 0f), new Vector3(0.018f, 2.0f, 0.35f), 0.002f, Wood);
            b.Box(new Vector3(0.491f, 1.0f, 0f), new Vector3(0.018f, 2.0f, 0.35f), 0.002f, Wood);
            b.Box(new Vector3(0f, 1.0f, -0.17f), new Vector3(0.964f, 2.0f, 0.01f), 0f, Wood);
            foreach (float y in new[] { 0.009f, 0.409f, 0.809f, 1.209f, 1.609f, 1.991f })
                b.Box(new Vector3(0f, y, 0.005f), new Vector3(0.964f, 0.018f, 0.34f), 0.002f, Wood);

            // ---------- книги: простые коробки, без скоса — их 90, бюджет важнее
            for (int i = 0; i < Books.GetLength(0); i++)
            {
                var c = new Vector3(Books[i, 0], Books[i, 1], Books[i, 2]);
                var s = new Vector3(Books[i, 3], Books[i, 4], Books[i, 5]);
                var rot = Quaternion.Euler(0f, Books[i, 6], Books[i, 7]);
                b.Box(c, s, 0f, (int)Books[i, 8], rot);
            }

            Mesh mesh = b.Bake("SM_Shelf", 4);
            PBKit.Log("Shelf", mesh);

            PBKit.EditPrefab("PRB_Shelf", root =>
            {
                GameObject m = PBKit.SetMeshChild(root.transform, "Mesh", mesh,
                    PBKit.Mat("MAT_Desk_Wood"), PBKit.Mat("MAT_Plastic"), PBKit.Mat("MAT_Fabric"), PBKit.Mat("MAT_Paper"));
                PBKit.FitBox(root.GetComponent<BoxCollider>(), mesh, m.transform, root.transform);
            });
        }
